package sentinel_test

import (
	"testing"

	"go.thesmos.sh/testkit"
	"go.thesmos.sh/testkit/generator"
	"go.thesmos.sh/testkit/generator/sentinel"
)

func TestGenerator(t *testing.T) {
	t.Parallel()

	t.Run("Name returns sentinel", func(t *testing.T) {
		t.Parallel()
		g := &sentinel.Generator{}
		testkit.Equal(t, g.Name(), "sentinel", "subcommand name")
	})

	t.Run("Generate produces a single output file against the basic fixture", func(t *testing.T) {
		t.Parallel()
		pkg := loadBasic(t)
		g := &sentinel.Generator{}
		res, err := g.Generate(pkg, nil, generator.DefaultConfig(), generator.Options{
			Output: "errors.gen_test.go",
		})
		testkit.NoError(t, err, "Generate")
		testkit.Len(t, res.Files, 1, "single file emitted")
		testkit.Equal(t, res.Files[0].Path, "errors.gen_test.go", "Path matches Output")
	})

	t.Run("output contains expected test functions and assertions", func(t *testing.T) {
		t.Parallel()
		pkg := loadBasic(t)
		g := &sentinel.Generator{}
		res, err := g.Generate(pkg, nil, generator.DefaultConfig(), generator.Options{
			Output: "errors.gen_test.go",
		})
		testkit.NoError(t, err, "Generate")
		testkit.Assert(t, string(res.Files[0].Content)).
			Contains("TestBasicSentinelErrors", "top-level sentinel test function").
			Contains("ErrNotFound", "sentinel var").
			Contains("ErrConflict", "sentinel var").
			Contains("ErrForbidden", "sentinel var").
			Contains("prefix", "prefix subtest").
			Contains("uniqueness", "uniqueness subtest").
			Contains("non-overlap", "non-overlap subtest").
			Contains("errors.Join chain", "errors.Join chain subtest").
			Contains("fmt.Errorf chain", "fmt.Errorf chain subtest").
			Contains("TestValidationError", "error-type test").
			Contains("TestNotFoundError", "Is-method test").
			Contains("TestWrappedError", "Unwrap-method test").
			Contains("does not match other error types", "cross-error-type non-overlap").
			Contains("Unwrap returns nil when cause is unset", "Unwrap-nil subtest").
			Contains("ContainsInOrder", "format-strictness assertion").
			Contains("errors.As", "errors.As assertion")
	})

	t.Run("source file filter limits Err* vars", func(t *testing.T) {
		t.Parallel()
		pkg := loadBasic(t)
		g := &sentinel.Generator{}
		res, err := g.Generate(pkg, nil, generator.DefaultConfig(), generator.Options{
			Output:     "errors.gen_test.go",
			SourceFile: "nonexistent.go",
		})
		testkit.NoError(t, err, "Generate")
		// Sentinels filtered out, but error types still present.
		testkit.Len(t, res.Files, 1, "error types still produce output")
		testkit.Assert(t, string(res.Files[0].Content)).
			NotContains("ErrNotFound", "filtered Err* vars must not appear").
			Contains("TestValidationError", "error types still emitted")
	})

	t.Run("output documents what each test asserts and which directives drove it", func(t *testing.T) {
		t.Parallel()
		pkg := loadBasic(t)
		g := &sentinel.Generator{}
		res, err := g.Generate(pkg, nil, generator.DefaultConfig(), generator.Options{
			Output: "errors.gen_test.go",
		})
		testkit.NoError(t, err, "Generate")
		got := string(res.Files[0].Content)
		testkit.Assert(t, got).
			Contains("// This file verifies", "file-level doc summary").
			Contains("Directives consumed:", "consumed-directives header").
			Contains("//testkit:sentinel-no-overlap-with go.thesmos.sh/testkit/generator/testdata/storage",
				"directive surfaced in header doc").
			Contains("// TestBasicSentinelErrors verifies", "sentinel-vars function doc").
			Contains("// TestNotFoundError verifies", "error-type function doc").
			Contains("// TestBasicSentinelErrorsNoOverlapWithStorage", "cross-pkg function doc").
			Contains("Driven by:", "cross-pkg directive attribution").
			Contains(`// "prefix":`, "subtest comment").
			Contains("Each custom error type must be distinct", "non-overlap subtest comment")
	})

	t.Run("output is gofmt-clean", func(t *testing.T) {
		t.Parallel()
		pkg := loadBasic(t)
		g := &sentinel.Generator{}
		res, err := g.Generate(pkg, nil, generator.DefaultConfig(), generator.Options{
			Output: "errors.gen_test.go",
		})
		testkit.NoError(t, err, "Generate")
		// goimports already ran inside the pipeline. We just verify the
		// output begins with the canonical generated header so renderers
		// haven't dropped it.
		testkit.Assert(t, string(res.Files[0].Content)).
			Contains("// Code generated by testkit sentinel. DO NOT EDIT.", "header preserved")
	})
}
