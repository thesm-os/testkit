func TestRender(t *testing.T) {
	t.Parallel()

	t.Run("emits header, source attribution, and template body", func(t *testing.T) {
		t.Parallel()
		out, err := generator.Render(`package p

func F() {}
`, nil, generator.Header{
			Subcommand: "stub",
			Args:       "stub Store",
			SourceFile: "store.go:1-10",
		})
		testkit.NoError(t, err, "Render")
		testkit.Assert(t, string(out)).
			Contains("// Code generated by testkit stub. DO NOT EDIT.", "generated header").
			Contains("// Source: store.go:1-10 (testkit stub Store)", "source attribution").
			Contains("func F() {}", "template body")
	})

	t.Run("emits build tag prefix when set", func(t *testing.T) {
		t.Parallel()
		out, err := generator.Render(`package p`, nil, generator.Header{
			Subcommand: "stub",
			BuildTag:   "integration",
		})
		testkit.NoError(t, err, "Render")
		testkit.True(t, strings.HasPrefix(string(out), "//go:build integration\n"), "build-tag prefix")
	})

	t.Run("template execution errors propagate", func(t *testing.T) {
		t.Parallel()
		_, err := generator.Render(`{{.NoSuchField}}`, struct{}{}, generator.Header{Subcommand: "x"})
		testkit.True(t, err != nil, "missing field should error")
	})
}

func TestFuncMap(t *testing.T) {
	t.Parallel()

	t.Run("string helpers route to package functions", func(t *testing.T) {
		t.Parallel()
		fm := generator.FuncMap()
		cases := []struct {
			fn   string
			in   string
			want string
		}{
			{"toLower", "FOO", "foo"},
			{"toUpper", "foo", "FOO"},
			{"title", "id", "ID"},
			{"camelCase", "http_method", "HTTPMethod"},
			{"lowerCamelCase", "http_method", "hTTPMethod"},
			{"snakeCase", "UserID", "user_i_d"},
		}
		for _, tc := range cases {
			fn := fm[tc.fn].(func(string) string)
			testkit.Equal(t, fn(tc.in), tc.want, tc.fn+"("+tc.in+")")
		}
	})

	t.Run("arithmetic helpers add/sub work", func(t *testing.T) {
		t.Parallel()
		fm := generator.FuncMap()
		add := fm["add"].(func(int, int) int)
		sub := fm["sub"].(func(int, int) int)
		testkit.Equal(t, add(2, 3), 5, "add(2,3)")
		testkit.Equal(t, sub(10, 4), 6, "sub(10,4)")
	})

	t.Run("dict assembles a string-keyed map from alternating args", func(t *testing.T) {
		t.Parallel()
		tmpl, err := generator.NewTemplateSet().Parse(`{{$d := dict "k" 1 "v" "x"}}{{$d.k}}-{{$d.v}}`)
		testkit.NoError(t, err, "Parse")
		var sb strings.Builder
		testkit.NoError(t, tmpl.Execute(&sb, nil), "Execute")
		testkit.Equal(t, sb.String(), "1-x", "dict accessible via field syntax")
	})

	t.Run("dict surfaces odd-args and non-string-key errors at execute time", func(t *testing.T) {
		t.Parallel()
		// Odd number of args.
		tmpl, err := generator.NewTemplateSet().Parse(`{{dict "a"}}`)
		testkit.NoError(t, err, "Parse")
		var sb strings.Builder
		testkit.True(t, tmpl.Execute(&sb, nil) != nil, "odd args must error")

		// Non-string key.
		tmpl, err = generator.NewTemplateSet().Parse(`{{dict 1 "v"}}`)
		testkit.NoError(t, err, "Parse")
		sb.Reset()
		testkit.True(t, tmpl.Execute(&sb, nil) != nil, "non-string key must error")
	})

	t.Run("NewTemplateSet inherits the FuncMap", func(t *testing.T) {
		t.Parallel()
		tmpl, err := generator.NewTemplateSet().Parse(`{{toUpper "hello"}}`)
		testkit.NoError(t, err, "Parse")
		var sb strings.Builder
		testkit.NoError(t, tmpl.Execute(&sb, nil), "Execute")
		testkit.Equal(t, sb.String(), "HELLO", "FuncMap available in template")
	})

	t.Run("string utility helpers in FuncMap match templates", func(t *testing.T) {
		t.Parallel()
		fm := generator.FuncMap()
		quote := fm["quote"].(func(string) string)
		testkit.Equal(t, quote(`a"b`), `"a\"b"`, "quote escapes")

		joinFn := fm["join"].(func([]string, string) string)
		testkit.Equal(t, joinFn([]string{"a", "b", "c"}, ","), "a,b,c", "join separator")
	})

	t.Run("type-introspection FuncMap helpers route correctly", func(t *testing.T) {
		t.Parallel()
		const src = `package p
import (
	"context"
)
type I interface {
	Slice() []int
	Map() map[string]int
	Chan() chan int
	Pointer() *int
	Ctx(ctx context.Context)
	Err() error
}
`
		iface, _ := loadIface(t, src, "I")
		fm := generator.FuncMap()
		isSlice := fm["isSlice"].(func(types.Type) bool)
		isMap := fm["isMap"].(func(types.Type) bool)
		isChan := fm["isChan"].(func(types.Type) bool)
		isPointer := fm["isPointer"].(func(types.Type) bool)
		isCtx := fm["isContext"].(func(types.Type) bool)
		isErr := fm["isError"].(func(types.Type) bool)

		testkit.True(t, isSlice(methodSig(t, iface, "Slice").Results().At(0).Type()), "isSlice")
		testkit.True(t, isMap(methodSig(t, iface, "Map").Results().At(0).Type()), "isMap")
		testkit.True(t, isChan(methodSig(t, iface, "Chan").Results().At(0).Type()), "isChan")
		testkit.True(t, isPointer(methodSig(t, iface, "Pointer").Results().At(0).Type()), "isPointer")
		testkit.True(t, isCtx(methodSig(t, iface, "Ctx").Params().At(0).Type()), "isContext")
		testkit.True(t, isErr(methodSig(t, iface, "Err").Results().At(0).Type()), "isError")
	})
}
