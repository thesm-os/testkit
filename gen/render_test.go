func TestFuncMap(t *testing.T) {
	t.Parallel()
	fm := gen.FuncMap()

	t.Run("contains all expected functions", func(t *testing.T) {
		t.Parallel()
		expected := []string{
			"toLower", "toUpper", "title", "camelCase", "lowerCamelCase",
			"snakeCase", "join", "quote", "isContext", "isError",
			"isPointer", "isSlice", "isMap", "isChan",
		}
		for _, name := range expected {
			testkit.True(t, fm[name] != nil, "must have "+name)
		}
	})

	t.Run("functions work in template", func(t *testing.T) {
		t.Parallel()
		tmpl := `package foo

const A = "{{ toLower "HELLO" }}"
const B = "{{ toUpper "hello" }}"
const C = "{{ title "id" }}"
const D = "{{ camelCase "hello_world" }}"
const E = "{{ lowerCamelCase "hello_world" }}"
const F = "{{ snakeCase "HelloWorld" }}"
const G = {{ quote "test" }}
`
		got, err := gen.Render(tmpl, nil, gen.Header{Subcommand: "test"})
		testkit.NoError(t, err, "render must succeed")
		s := string(got)
		testkit.Assert(t, s).
			Contains(`"hello"`, "toLower").
			Contains(`"HELLO"`, "toUpper").
			Contains(`"ID"`, "title with initialism").
			Contains(`"HelloWorld"`, "camelCase").
			Contains(`"helloWorld"`, "lowerCamelCase").
			Contains(`"hello_world"`, "snakeCase")
	})
}

func TestRender(t *testing.T) {
	t.Parallel()

	t.Run("produces valid Go with header", func(t *testing.T) {
		t.Parallel()
		tmpl := `package foo

func Hello() string { return "hello" }
`
		header := gen.Header{Subcommand: "test", Args: "test -o foo.go"}
		got, err := gen.Render(tmpl, nil, header)
		testkit.NoError(t, err, "render must succeed")
		s := string(got)
		testkit.Assert(t, s).
			Contains("Code generated by testkit test", "must have header").
			Contains("Source: testkit test -o foo.go", "must have source line").
			Contains("package foo", "must have package declaration")
	})

	t.Run("includes build tag when set", func(t *testing.T) {
		t.Parallel()
		tmpl := `package foo
`
		header := gen.Header{Subcommand: "integration", BuildTag: "integration"}
		got, err := gen.Render(tmpl, nil, header)
		testkit.NoError(t, err, "render must succeed")
		testkit.Assert(t, string(got)).Contains("//go:build integration", "must have build tag")
	})

	t.Run("goimports adds missing imports", func(t *testing.T) {
		t.Parallel()
		tmpl := `package foo

func F() { fmt.Println("hello") }
`
		got, err := gen.Render(tmpl, nil, gen.Header{Subcommand: "test"})
		testkit.NoError(t, err, "render must succeed")
		testkit.Assert(t, string(got)).Contains(`"fmt"`, "must add fmt import")
	})

	t.Run("template data is accessible", func(t *testing.T) {
		t.Parallel()
		tmpl := `package foo

const Name = "{{.Name}}"
`
		data := struct{ Name string }{"World"}
		got, err := gen.Render(tmpl, data, gen.Header{Subcommand: "test"})
		testkit.NoError(t, err, "render must succeed")
		testkit.Assert(t, string(got)).Contains(`"World"`, "must render data")
	})

	t.Run("invalid template returns error", func(t *testing.T) {
		t.Parallel()
		_, err := gen.Render(`{{.Invalid`, nil, gen.Header{Subcommand: "test"})
		testkit.Error(t, err, "must fail on invalid template")
	})

	t.Run("template execution error returns error", func(t *testing.T) {
		t.Parallel()
		_, err := gen.Render(`package foo
{{.Missing.Field}}`, nil, gen.Header{Subcommand: "test"})
		testkit.Error(t, err, "must fail on execution error")
	})

	t.Run("omits Source line when Args empty", func(t *testing.T) {
		t.Parallel()
		tmpl := `package foo
`
		got, err := gen.Render(tmpl, nil, gen.Header{Subcommand: "test"})
		testkit.NoError(t, err, "render must succeed")
		testkit.Assert(t, string(got)).NotContains("Source:", "must omit source line")
	})

	t.Run("executes named template", func(t *testing.T) {
		t.Parallel()
		set := gen.NewTemplateSet()
		_, err := set.Parse(`{{define "main"}}package foo
func F() {}
{{end}}`)
		testkit.NoError(t, err, "parse must succeed")
		got, renderErr := gen.RenderTemplate(set, "main", nil, gen.Header{Subcommand: "test"})
		testkit.NoError(t, renderErr, "render must succeed")
		testkit.Assert(t, string(got)).Contains("func F()", "must render named template")
	})
}
