package gen

import (
	"bytes"
	"fmt"
	"go/types"
	"strconv"
	"strings"
	"text/template"

	"golang.org/x/tools/imports"
)

const (
	generatedHeaderFmt = "// Code generated by testkit %s. DO NOT EDIT.\n"
	sourceHeaderFmt    = "// Source: testkit %s\n"
	buildTagFmt        = "//go:build %s\n\n"
	goimportsFilename  = "generated.go"
)

// Header describes the generated-file header comment.
type Header struct {
	Subcommand string // "stub", "recording", etc.
	Args       string // original command-line args for traceability
	BuildTag   string // optional //go:build tag, empty for most generators
}

// FuncMap returns the standard template function map available to all
// generator templates.
func FuncMap() template.FuncMap {
	return template.FuncMap{
		"toLower":        strings.ToLower,
		"toUpper":        strings.ToUpper,
		"title":          Title,
		"camelCase":      CamelCase,
		"lowerCamelCase": LowerCamelCase,
		"snakeCase":      SnakeCase,
		"join":           strings.Join,
		"quote":          strconv.Quote,
		"isContext":      isContextType,
		"isError":        isErrorType,
		"isPointer":      func(t types.Type) bool { _, ok := t.(*types.Pointer); return ok },
		"isSlice":        func(t types.Type) bool { _, ok := t.Underlying().(*types.Slice); return ok },
		"isMap":          func(t types.Type) bool { _, ok := t.Underlying().(*types.Map); return ok },
		"isChan":         func(t types.Type) bool { _, ok := t.Underlying().(*types.Chan); return ok },
	}
}

// NewTemplateSet returns a [template.Template] pre-loaded with the
// standard function map. Generator templates are parsed into this set
// to inherit the shared functions.
func NewTemplateSet() *template.Template {
	return template.New("").Funcs(FuncMap())
}

// Render executes tmplText with data, prepends the generated-file
// header, and formats with goimports. Returns formatted Go source.
func Render(tmplText string, data any, header Header) ([]byte, error) {
	tmpl, err := NewTemplateSet().Parse(tmplText)
	if err != nil {
		return nil, fmt.Errorf("parse template: %w", err)
	}
	return RenderTemplate(tmpl, "", data, header)
}

// RenderTemplate executes a pre-parsed template by name (empty for
// the root template), prepends header, and formats with goimports.
func RenderTemplate(tmpl *template.Template, name string, data any, header Header) ([]byte, error) {
	var buf bytes.Buffer

	// Build tag.
	if header.BuildTag != "" {
		fmt.Fprintf(&buf, buildTagFmt, header.BuildTag)
	}

	// Generated file header.
	fmt.Fprintf(&buf, generatedHeaderFmt, header.Subcommand)
	if header.Args != "" {
		fmt.Fprintf(&buf, sourceHeaderFmt, header.Args)
	}
	buf.WriteString("\n")

	// Execute template.
	var execErr error
	if name != "" {
		execErr = tmpl.ExecuteTemplate(&buf, name, data)
	} else {
		execErr = tmpl.Execute(&buf, data)
	}
	if execErr != nil {
		return nil, fmt.Errorf("execute template: %w", execErr)
	}

	// Format with goimports.
	formatted, err := imports.Process(goimportsFilename, buf.Bytes(), &imports.Options{
		Comments:  true,
		TabIndent: true,
		TabWidth:  8,
	})
	if err != nil {
		return nil, fmt.Errorf("goimports: %w\n\nraw output:\n%s", err, buf.String())
	}
	return formatted, nil
}

