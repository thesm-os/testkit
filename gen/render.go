// commonInitialisms is the set of Go-conventional initialisms that
// should be fully uppercased in exported names. Matches the set used
// by golint/staticcheck.
var commonInitialisms = map[string]bool{
	"ACL":   true,
	"API":   true,
	"ASCII": true,
	"CPU":   true,
	"CSS":   true,
	"DNS":   true,
	"EOF":   true,
	"GUID":  true,
	"HTML":  true,
	"HTTP":  true,
	"HTTPS": true,
	"ID":    true,
	"IP":    true,
	"JSON":  true,
	"LHS":   true,
	"QPS":   true,
	"RAM":   true,
	"RHS":   true,
	"RPC":   true,
	"SLA":   true,
	"SMTP":  true,
	"SQL":   true,
	"SSH":   true,
	"TCP":   true,
	"TLS":   true,
	"TTL":   true,
	"UDP":   true,
	"UI":    true,
	"UID":   true,
	"URI":   true,
	"URL":   true,
	"UTF8":  true,
	"UUID":  true,
	"VM":    true,
	"XML":   true,
	"XMPP":  true,
	"XSS":   true,
}

// title uppercases the first letter of s, with awareness of Go
// initialisms. "id" → "ID", "url" → "URL", "name" → "Name".
func title(s string) string {
	if s == "" {
		return s
	}
	upper := strings.ToUpper(s)
	if commonInitialisms[upper] {
		return upper
	}
	r := []rune(s)
	r[0] = unicode.ToUpper(r[0])
	return string(r)
}

func camelCase(s string) string {
	parts := splitWords(s)
	for i := range parts {
		parts[i] = title(strings.ToLower(parts[i]))
	}
	return strings.Join(parts, "")
}

func lowerCamelCase(s string) string {
	c := camelCase(s)
	if c == "" {
		return c
	}
	r := []rune(c)
	r[0] = unicode.ToLower(r[0])
	return string(r)
}

func snakeCase(s string) string {
	parts := splitWords(s)
	for i := range parts {
		parts[i] = strings.ToLower(parts[i])
	}
	return strings.Join(parts, "_")
}

// splitWords splits a string into words on underscores, hyphens, and
// CamelCase boundaries.
func splitWords(s string) []string {
	var words []string
	var current []rune
	for i, r := range s {
		switch {
		case r == '_' || r == '-':
			if len(current) > 0 {
				words = append(words, string(current))
				current = nil
			}
		case unicode.IsUpper(r) && i > 0 && !unicode.IsUpper(rune(s[i-1])):
			if len(current) > 0 {
				words = append(words, string(current))
				current = nil
			}
			current = append(current, r)
		default:
			current = append(current, r)
		}
	}
	if len(current) > 0 {
		words = append(words, string(current))
	}
	return words
}
